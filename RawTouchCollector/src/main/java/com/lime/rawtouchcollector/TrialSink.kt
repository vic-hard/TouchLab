package com.lime.rawtouchcollector

/**
 * Структурный уровень выдачи: точка расширения для слоя хранения.
 *
 * Реализация получает готовый неизменяемый снимок и должна вернуть true только после
 * фактической фиксации данных — транзакции Room либо эквивалентной принудительной
 * записи. Возврат false или брошенное исключение считаются ошибкой записи,
 * и попытка не будет отмечена подтверждённой.
 *
 * Вызывается на фоновом потоке коллектора; блокирующая работа здесь допустима.
 */
public interface TrialSink {
    public fun persist(trial: TrialSnapshot): Boolean
}
